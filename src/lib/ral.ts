const table = new Map<string, string>(
  RAL_CLASSIC_HEX.trim()
    .split(/\s+/)
    .map((entry) => {
      const [code, hex] = entry.split(":");
      return [code, `#${hex.toLowerCase()}`];
    }),
);

/** Matches "RAL 7016", "ral7016" or "RAL-7016"; a bare number is not enough. */
const RAL_CODE = /\bRAL[\s.-]*(\d{4})\b/i;

/** Approximate hex for the RAL Classic code found in `text`, or null. */
export function ralHex(text: string | null | undefined): string | null {
  const match = text?.match(RAL_CODE);
  return match ? (table.get(match[1]) ?? null) : null;
}

